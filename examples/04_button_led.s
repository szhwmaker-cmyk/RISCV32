# =====================================================
# 示例程序 4: 按钮控制LED
# =====================================================
# 功能：读取按钮状态，控制LED亮灭
# 外设：GPIO (基地址 0x20001000)
# 难度：⭐⭐ 初级
# =====================================================
# GPIO映射：
#   GPIO[3:0] - LED输出
#   GPIO[7:4] - 按钮输入
# =====================================================

.section .text
.globl _start

_start:
    # ========== 初始化GPIO ==========
    lui  x1, 0x20001            # x1 = GPIO_BASE = 0x20001000

    # 设置GPIO方向
    # GPIO[3:0] = 输出 (LED)
    # GPIO[7:4] = 输入 (按钮)
    addi x2, x0, 0x0F           # x2 = 0x0F (低4位为输出)
    sw   x2, 4(x1)              # GPIO_DIR = 0x0F

    # 设置GPIO输出使能
    addi x2, x0, 0x0F           # 使能低4位输出
    sw   x2, 8(x1)              # GPIO_OE = 0x0F

main_loop:
    # ========== 读取GPIO输入 ==========
    lw   x3, 0(x1)              # x3 = GPIO_DATA

    # 提取按钮状态（GPIO[7:4]）
    srli x4, x3, 4              # x4 = x3 >> 4（按钮位移到低4位）
    andi x4, x4, 0x0F           # 只保留低4位

    # ========== 根据按钮控制LED ==========
    # 简单映射：按钮直接控制对应LED
    # BTN[0] → LED[0]
    # BTN[1] → LED[1]
    # BTN[2] → LED[2]
    # BTN[3] → LED[3]

    sw   x4, 0(x1)              # GPIO_DATA[3:0] = 按钮状态

    # ========== 小延时（消抖） ==========
    addi x5, x0, 100            # 延时计数

debounce_delay:
    addi x5, x5, -1
    bne  x5, x0, debounce_delay

    # ========== 继续循环 ==========
    beq  x0, x0, main_loop

# =====================================================
# 预期行为：
# - 按下BTN0 → LED0亮
# - 按下BTN1 → LED1亮
# - 按下BTN2 → LED2亮
# - 按下BTN3 → LED3亮
# - 松开按钮 → 对应LED灭
#
# 可以同时按下多个按钮，对应LED都会亮
# =====================================================
